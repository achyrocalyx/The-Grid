void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart) {
    __HAL_UART_CLEAR_PEFLAG(huart);   // clears ORE/NE/FE/PE flags on this family
    HAL_UART_Receive_IT(&huart3, switch_data_buffer, SWITCH_DATA_LENGTH);
}

/* Module switch data receive callback function */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	if (resyncing) {
		resyncing = 0;
		HAL_UART_Receive_IT(&huart3, switch_data_buffer, SWITCH_DATA_LENGTH);
		return;
	}
	/* If we are out of sync with microswitch data...eek!!!! */
	if (switch_data_buffer[1] & 0xF0) {
		resyncing = 1;
		HAL_UART_Receive_IT(&huart3, sync_bytes, 3);
		return;
	}
	if (state == IDLE) {
		send_switch_data_flag = true;
		memcpy(switch_data_tx_buffer, switch_data_buffer, SWITCH_DATA_LENGTH);
	}
	HAL_UART_Receive_IT(&huart3, switch_data_buffer, SWITCH_DATA_LENGTH);
}

/* Frame data transmit completed callback function */
void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart) {
	HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, 0); // Pull DE pin low
	state = IDLE;
}

